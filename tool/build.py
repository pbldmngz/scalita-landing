# Order matters: it is the order of the language menu, and English is first
# because it is the default the bare domain serves.
LOCALES = [
    # code, url path, <html lang>, hreflang, og:locale, native name
    ("en", "/",     "en",    "en",    "en_US", "English"),
    ("es", "/es/",  "es",    "es",    "es_ES", "Español"),
    ("fr", "/fr/",  "fr",    "fr",    "fr_FR", "Français"),
    ("pt", "/pt/",  "pt-BR", "pt-BR", "pt_BR", "Português"),
    ("de", "/de/",  "de",    "de",    "de_DE", "Deutsch"),
]

