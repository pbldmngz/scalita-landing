def main():
    written = []
    for loc in LOCALES:
        code, loc_path = loc[0], loc[1]
        with open(os.path.join(CONTENT, code + ".json"), encoding="utf-8") as fh:
            c = json.load(fh)
        outdir = ROOT if loc_path == "/" else os.path.join(ROOT, code)
        os.makedirs(outdir, exist_ok=True)
        for page in PAGES:
            html = build_index(loc, c) if page == "index" else build_text_page(loc, c, page)
            path = os.path.join(outdir, page + ".html")
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(html)
            written.append(os.path.relpath(path, ROOT))
    with open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8") as fh:
        fh.write(build_sitemap())
    written.append("sitemap.xml")
    for w in written:
        print("wrote", w)


if __name__ == "__main__":
    main()
