# What a routine's player needs of a scale it plays: the pattern, not the
# single scale player's presets or the usage counts.
SCALE_IN_ROUTINE_DROPS = ("presets", "routinesUsing", "stepsUsing", "hash")


def player_data(kind, item_id, code):
    """What the player widget needs for one routine or scale: its export
    entry localized (tool/data/README.md has the fields), plus kind, and for
    a routine every scale its steps use, under scales (without the scale's
    own presets, usage counts and hash)."""
    if kind not in ("routine", "scale"):
        raise BuildError("player_data(): kind is 'routine' or 'scale', not %r" % kind)
    stem = kind + "s"
    entry = find_entry(stem, item_id)
    if entry is None:
        if data(stem) is None:
            missing("tool/data/app/%s.json does not exist yet" % stem)
            return {"kind": kind, "id": item_id}
        raise BuildError("tool/data/app/%s.json has no %r" % (stem, item_id))
    out = {"kind": kind}
    out.update(localize(entry, code))
    if kind == "routine":
        out["scales"] = {}
        for step in entry.get("steps") or []:
            sid = step.get("scaleId")
            if sid and sid not in out["scales"]:
                scale = find_entry("scales", sid)
                if scale is not None:
                    out["scales"][sid] = localize(
                        {k: v for k, v in scale.items() if k not in SCALE_IN_ROUTINE_DROPS}, code)
    return out


