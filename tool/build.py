def load_json(path, what=None):
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except ValueError as e:
        raise BuildError("%s is not valid JSON: %s" % (what or rel(path), e))


def shape_diff(ref, other, path=""):
    """Every way a translation differs in shape from the English: a key
    missing or extra at any depth, a list of another length. A null on
    either side is not compared (a locale box only one language fills)."""
    if ref is None or other is None:
        return []
    if isinstance(ref, dict):
        if not isinstance(other, dict):
            return ["%s is not an object" % (path.rstrip(".") or "the file")]
        out = ["%s%s is missing" % (path, k) for k in ref if k not in other]
        out += ["%s%s is extra" % (path, k) for k in other if k not in ref]
        for k in ref:
            if k in other:
                out += shape_diff(ref[k], other[k], "%s%s." % (path, k))
        return out
    if isinstance(ref, list):
        if not isinstance(other, list):
            return ["%s is not a list" % path.rstrip(".")]
        if len(ref) != len(other):
            return ["%s has %d items, the English has %d" % (path.rstrip("."), len(other), len(ref))]
        out = []
        for n, (a, b) in enumerate(zip(ref, other)):
            out += shape_diff(a, b, "%s%d." % (path, n))
        return out
    return []


def page_file(code, name):
    return os.path.join(S.content, "pages", code, name + ".json")


def load_sites():
    for code, *_ in LOCALES:
        path = os.path.join(S.content, code + ".json")
        if not os.path.exists(path):
            if code == "en":
                raise BuildError("%s is missing" % rel(path))
            missing("%s is missing, so %s is not built" % (rel(path), code))
            continue
        S.site[code] = load_json(path)
    for code, c in S.site.items():
        diff = shape_diff(S.site["en"], c)
        if diff:
            raise BuildError("%s.json does not have the keys en.json has: %s" % (code, "; ".join(diff[:10])))
        words = [c["sections"][s] for s in SECTIONS]
        for w in words:
            if not isinstance(w, str) or not SLUG.match(w):
                raise BuildError("%s.json: section word %r is not lowercase ASCII words joined by hyphens"
                                 % (code, w))
            if code == "en" and w in RESERVED:
                raise BuildError("en.json: section word %r is taken at the site root" % w)
        if len(set(words)) != len(words):
            raise BuildError("%s.json: the two section words are the same" % code)


def load_registry():
    reg = load_json(os.path.join(TOOL, "pages.json"))
    ids = {}
    for p in reg:
        for k in ("id", "section", "template", "data", "hub", "parent"):
            if k not in p:
                raise BuildError("tool/pages.json: %s has no %r" % (p.get("id", p), k))
        if not SLUG.match(p["id"]) or p["id"] in ids:
            raise BuildError("tool/pages.json: id %r is not a slug, or is used twice" % p["id"])
        if p["section"] not in ("legacy",) + SECTIONS:
            raise BuildError("tool/pages.json: %s has section %r" % (p["id"], p["section"]))
        if (p["section"] == "legacy") != (p["template"] in ("legacy-home", "legacy-text")):
            raise BuildError("tool/pages.json: %s: the legacy templates are for legacy pages only" % p["id"])
        if p["section"] != "legacy" and not re.fullmatch(r"[a-z_]+", p["template"]):
            raise BuildError("tool/pages.json: %s has template %r" % (p["id"], p["template"]))
        ids[p["id"]] = p
    if [p["id"] for p in reg if p["template"] == "legacy-home"] != ["index"]:
        raise BuildError("tool/pages.json: the home page is id 'index' with template 'legacy-home'")
    for section in SECTIONS:
        if len([p for p in reg if p["section"] == section and p.get("root")]) > 1:
            raise BuildError("tool/pages.json: section %s has more than one root page" % section)
    for p in reg:
        seen, q = {p["id"]}, p
        while q["parent"] is not None:
            if q["parent"] not in ids:
                raise BuildError("tool/pages.json: %s has an unknown parent %r" % (q["id"], q["parent"]))
            q = ids[q["parent"]]
            if q["id"] in seen:
                raise BuildError("tool/pages.json: the parents of %s go round in a loop" % p["id"])
            seen.add(q["id"])
    S.registry = reg
    S.by_id = ids


def check_copy(page, code, copy, path):
    """What the build itself needs from a page file. check.py checks the rest."""
    for k in ("label", "title", "description"):
        if not isinstance(copy.get(k), str) or not copy[k].strip():
            raise BuildError("%s: %r is missing or empty" % (rel(path), k))
    if page.get("root"):
        if "slug" in copy:
            raise BuildError("%s: a section's root page has no slug, its URL is the section word" % rel(path))
    elif not isinstance(copy.get("slug"), str) or not SLUG.match(copy["slug"]):
        raise BuildError("%s: slug %r is not lowercase ASCII words joined by hyphens"
                         % (rel(path), copy.get("slug")))


def load_pages():
    for page in S.registry:
        if page["section"] == "legacy":
            continue
        pid = page["id"]
        if not os.path.exists(os.path.join(TEMPLATES, page["template"] + ".py")):
            missing("tool/templates/%s.py does not exist yet, so %s is not built" % (page["template"], pid))
            continue
        en_path = page_file("en", pid)
        if not os.path.exists(en_path):
            missing("%s is missing, so %s is not built" % (rel(en_path), pid))
            continue
        en = load_json(en_path)
        for code in S.site:
            path = page_file(code, pid)
            if code == "en":
                copy = en
            elif not os.path.exists(path):
                missing("%s is missing, so %s is not built in %s" % (rel(path), pid, code))
                continue
            else:
                copy = load_json(path)
                diff = shape_diff(en, copy)
                if diff:
                    raise BuildError("%s does not have the keys the English file has: %s"
                                     % (rel(path), "; ".join(diff[:10])))
            check_copy(page, code, copy, path)
            S.copy[(pid, code)] = copy


