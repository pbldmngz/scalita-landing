NOTE_TOKEN = re.compile(r"\{\{note:([^{}:]+)(?::(local|intl))?\}\}")
ANY_TOKEN = re.compile(r"\{\{.*?\}\}")
PAGE_LINK = re.compile(r'href="page:([^"#]*)(#[^"]*)?"')
UNLINK = "data-unlinked-page"


def resolve(s, code, where):
    """Fill the two tokens copy can carry. {{note:C4}} (or {{note:60}})
    becomes the key in the locale's notation with the international name,
    "do3 (C4)"; {{note:C4:local}} and {{note:C4:intl}} give one of the two.
    href="page:<id>" or href="page:<id>#anchor" becomes that page's URL in
    the locale. A link to a page this build skips keeps its words."""
    def note(m):
        midi = parse_note(m.group(1))
        if midi is None:
            raise BuildError("%s: %s is not a key from A0 to C8" % (where, m.group(0)))
        local, intl = note_table(code)[midi]
        return esc({"local": local, "intl": intl}.get(m.group(2)) or note_label(code, midi))

    def link(m):
        pid, frag = m.group(1), m.group(2) or ""
        if pid not in S.by_id:
            raise BuildError("%s links to %r, which is not in tool/pages.json" % (where, pid))
        if built(pid, code):
            return 'href="%s"' % url(pid, code, frag)
        missing("%s links to %s, which is not built in %s" % (where, pid, code))
        return UNLINK

    if "{{" in s:
        s = NOTE_TOKEN.sub(note, s)
        left = ANY_TOKEN.search(s)
        if left:
            raise BuildError("%s: unknown token %s" % (where, left.group(0)))
    if 'href="page:' in s:
        s = PAGE_LINK.sub(link, s)
        s = re.sub(r"<a\b[^>]*\b%s\b[^>]*>(.*?)</a>" % UNLINK, r"\1", s, flags=re.S)
    return s


def resolve_tree(obj, code, where, path=""):
    """resolve() every string of a content file; where names it in errors."""
    if isinstance(obj, str):
        return resolve(obj, code, "%s %s" % (where, path.rstrip(".")) if path else where)
    if isinstance(obj, list):
        return [resolve_tree(v, code, where, "%s%d." % (path, n)) for n, v in enumerate(obj)]
    if isinstance(obj, dict):
        return {k: resolve_tree(v, code, where, "%s%s." % (path, k)) for k, v in obj.items()}
    return obj


def resolve_all():
    for (pid, code), copy in list(S.copy.items()):
        S.copy[(pid, code)] = resolve_tree(copy, code, "pages/%s/%s.json" % (code, pid))
    for code, d in list(S.privacy_web.items()):
        S.privacy_web[code] = resolve_tree(d, code, "pages/%s/privacy-web.json" % code)
    for code, files in S.ui.items():
        for name in files:
            files[name] = resolve_tree(files[name], code, "ui/%s/%s.json" % (code, name))


