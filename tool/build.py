# A per-locale map loses its plural once it holds one locale's value.
RENAME = {"names": "name", "descriptions": "description", "labels": "label",
          "syllableByLocale": "syllableLocal"}


def is_locale_map(v):
    return isinstance(v, dict) and "en" in v and len(v) > 1 and set(v) <= CODES


def localize(obj, code):
    """Export data as one locale reads it: every {locale: value} map becomes
    that locale's value (English when it has none), and a map under names,
    descriptions, labels or syllableByLocale moves to name, description,
    label or syllableLocal. Everything else is copied as it is."""
    if isinstance(obj, list):
        return [localize(v, code) for v in obj]
    if not isinstance(obj, dict):
        return obj
    if is_locale_map(obj):
        return localize(obj.get(code, obj.get("en")), code)
    out = {}
    for k, v in obj.items():
        if is_locale_map(v):
            out[RENAME.get(k, k)] = localize(v.get(code, v.get("en")), code)
        else:
            out[k] = localize(v, code)
    return out


LETTERS = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
ACCIDENTALS = {"": 0, "#": 1, "♯": 1, "b": -1, "♭": -1}


def parse_note(text):
    """The MIDI number of "C4", "F#3", "Bb2" (scientific, middle C is C4) or
    "60", when it is a key of the piano, A0 to C8; None otherwise."""
    t = text.strip()
    if t.isdigit():
        midi = int(t)
    else:
        m = re.fullmatch("([A-G])([#b♯♭]?)(-?[0-9])", t)
        if not m:
            return None
        midi = 12 * (int(m.group(3)) + 1) + LETTERS[m.group(1)] + ACCIDENTALS[m.group(2)]
    return midi if 21 <= midi <= 108 else None


def intl_fallback(midi):
    return ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"][midi % 12] + str(midi // 12 - 1)


def note_table(code):
    """{midi: (local name, international name)} for a locale, A0 to C8, from
    tool/data/app/notes.json. Note names are never typed by hand."""
    if code not in S.notes:
        table = {}
        d = data("notes")
        rows = d.get(code) if isinstance(d, dict) else None
        if isinstance(rows, list):
            for r in rows:
                table[int(r["midi"])] = (r["name"], r["intl"])
        else:
            missing("tool/data/app/notes.json has no %s notes, so names fall back to C4 style" % code)
        for midi in range(21, 109):
            table.setdefault(midi, (intl_fallback(midi), intl_fallback(midi)))
        S.notes[code] = table
    return S.notes[code]


def note_label(code, midi):
    """A key in the locale's notation paired with the international name,
    "do3 (C4)", or just "C4" where the two are the same. Not escaped."""
    local, intl = note_table(code)[midi]
    return local if local == intl else "%s (%s)" % (local, intl)


