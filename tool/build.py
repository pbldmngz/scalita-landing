class UiView:
    """ctx.ui: ctx.ui["common"] is tool/content/ui/<locale>/common.json."""

    def __init__(self, code):
        self.code = code

    def __getitem__(self, name):
        return ui_strings(self.code, name)

    def get(self, name, default=None):
        return ui_strings(self.code, name) if name in S.ui_names else default


class DataView:
    """ctx.data: ctx.data["routines"] is tool/data/app/routines.json as the
    export wrote it (a missing file is an error that names it); .get(stem)
    returns None instead; .entry(stem, id) finds one entry by its id; and
    .local(stem, id=None) is that entry, or the whole file, localized."""

    def __init__(self, code):
        self.code = code

    def __getitem__(self, stem):
        d = data(stem)
        if d is None:
            raise BuildError("tool/data/app/%s.json is missing: run the export (tool/data/README.md)" % stem)
        return d

    def get(self, stem):
        return data(stem)

    def entry(self, stem, entry_id):
        return find_entry(stem, entry_id)

    def local(self, stem, entry_id=None):
        return localize(self[stem] if entry_id is None else find_entry(stem, entry_id), self.code)


class Ctx:
    """What a template's render(ctx) gets. tool/README.md, "Template
    contract", describes every field and helper."""

    def __init__(self, loc, page):
        self.loc = loc
        self.code = loc[0]
        self.lang = loc[2]
        self.site = S.site[self.code]
        self.page = page
        self.copy = S.copy.get((page["id"], self.code))
        self.data = DataView(self.code)
        self.ui = UiView(self.code)
        self.alternates = dict(alternates(page["id"]))
        self.registry = S.registry

    def url(self, page_id, frag=""):
        return url(page_id, self.code, frag)

    def url_abs(self, page_id):
        return url_abs(page_id, self.code)

    def has(self, page_id):
        return built(page_id, self.code)

    def asset(self, path, v=None):
        return asset(path, v)

    def play_link(self):
        return play_link(self.code, self.page["id"])

    def play_url(self):
        return play_url(self.code, self.page["id"])

    def inline_json(self, obj):
        return inline_json(obj)

    def esc(self, s):
        return esc(s)

    def label(self, page_id):
        return page_label(page_id, self.code)

    def copy_of(self, page_id):
        return S.copy.get((page_id, self.code))

    def breadcrumbs(self):
        return breadcrumbs(self.page["id"], self.code)

    def note(self, midi):
        return note_table(self.code)[midi]

    def note_label(self, midi):
        return esc(note_label(self.code, midi))

    def localize(self, obj):
        return localize(obj, self.code)

    def player_data(self, kind, item_id):
        return player_data(kind, item_id, self.code)

