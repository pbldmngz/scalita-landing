def parse_args(argv):
    ap = argparse.ArgumentParser(description="Build scalita.com from tool/content.")
    ap.add_argument("--out", default=ROOT,
                    help="the directory the site is written to (default: the repo root)")
    ap.add_argument("--content", default=os.path.join(TOOL, "content"),
                    help="the content directory (default: tool/content)")
    ap.add_argument("--allow-missing", action="store_true",
                    help="skip, with a warning, any page or locale whose content, template, "
                         "strings or data is not written yet")
    ap.add_argument("--record-published", action="store_true",
                    help="add every URL this build writes to tool/published-urls.txt, and date "
                         "what changed since the last commit, and every new URL, --today; "
                         "run it for the commit that publishes them")
    ap.add_argument("--today", default=datetime.date.today().isoformat(),
                    help="the date a page whose content changed gets as lastmod (default: today)")
    ap.add_argument("--page-data", metavar="PAGE_ID",
                    help="print the page data PAGE_ID carries in --locale, and write nothing")
    ap.add_argument("--locale", default="en", choices=[l[0] for l in LOCALES],
                    help="the locale for --page-data (default: en)")
    return ap.parse_args(argv)


def run(args):
    global S
    out = os.path.realpath(args.out)
    if out != ROOT and out.startswith(ROOT + os.sep):
        raise BuildError("--out is the repo root or a directory outside the repo, not %s" % out)
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.today):
        raise BuildError("--today is a date, YYYY-MM-DD")
    S = State(out, os.path.realpath(args.content), args.allow_missing, args.today)
    load_sites()
    load_registry()
    load_pages()
    load_privacy_web()
    load_ui()
    assign_paths()
    resolve_all()

    if args.page_data:
        print(json.dumps(dump_page_data(args.page_data, args.locale), ensure_ascii=False, indent=2))
        return

    lastmod = os.path.join(TOOL, "lastmod.json")
    S.lastmod_old = load_json(lastmod) if os.path.exists(lastmod) else {}
    header, published = read_published()
    if args.record_published:
        S.publish = (last_commit_date(), {row[0] for row in published})

    for loc in LOCALES:
        code = loc[0]
        if code not in S.site:
            continue
        c = S.site[code]
        for page in S.registry:
            if not built(page["id"], code):
                continue
            if page["template"] == "legacy-home":
                html, main = build_index(loc, c)
            elif page["template"] == "legacy-text":
                html, main = build_text_page(loc, c, page["id"])
            else:
                html, main = build_template_page(loc, page), None
            if main is not None:
                stamp_lastmod(url_abs(page["id"], code), main)
            write(S.paths[(page["id"], code)], html)

    write("/404.html", build_404())
    write_stubs(published)
    write_sitemaps()
    write("/robots.txt", ROBOTS)
    write("/.nojekyll", "")
    write_lastmod()
    if args.record_published:
        record_published(header, published)
    flush()
    remove_stale()
    link_static()
    for f in S.written:
        print("wrote", os.path.relpath(f, S.out))
    if S.warnings:
        print("%d warning(s), see above" % len(S.warnings), file=sys.stderr)


def main(argv=None):
    try:
        run(parse_args(argv))
    except BuildError as e:
        print("error: %s" % e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
