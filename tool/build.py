class DataView:
    """ctx.data: ctx.data["routines"] is tool/data/app/routines.json as the
    export wrote it (a missing file is an error that names it); .get(stem)
    returns None instead; .entry(stem, id) finds one entry by its id; and
    .local(stem, id=None) is that entry, or the whole file, localized."""

    def __init__(self, code):
        self.code = code

    def __getitem__(self, stem):
        d = data(stem)
        if d is None:
            raise BuildError("tool/data/app/%s.json is missing: run the export (tool/data/README.md)" % stem)
        return d

    def get(self, stem):
        return data(stem)

    def entry(self, stem, entry_id):
        return find_entry(stem, entry_id)

    def local(self, stem, entry_id=None):
        return localize(self[stem] if entry_id is None else find_entry(stem, entry_id), self.code)


