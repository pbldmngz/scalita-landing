def build_404():
    """One line in each language, each with its home and its two section
    homes. Pages serves this for a missing path at any depth, so every URL
    in it is root-absolute."""
    loc = LOC["en"]
    c = S.site["en"]
    rows = []
    for code, _, lang, _, _, _ in LOCALES:
        if code not in S.site:
            continue
        s = S.site[code]
        links = ['<a href="%s">%s</a>' % (url("index", code), esc(s["notFound"]["homes"]))]
        for section in SECTIONS:
            home = section_home(section, code)
            if home:
                links.append('<a href="%s">%s</a>' % (url(home, code), esc(s["nav"][section])))
        rows.append("""        <li lang="%s">
          <p>%s</p>
          <p class="notfound__links">%s</p>
        </li>""" % (lang, esc(s["notFound"]["line"]), "\n            ".join(links)))
    main = """  <main id="main">
  <section class="notfound">
    <div class="container">
      <h1>404</h1>
      <ul>
%s
      </ul>
    </div>
  </section>
  </main>""" % "\n".join(rows)
    return frame(loc, "404", main, BANNER_404, "%s - Scalita" % c["notFound"]["line"], c["notFound"]["line"],
                 links='  <meta name="robots" content="noindex">')


STUB = """<!--
  Generated by tool/build.py: this URL was published once and the page now
  lives at another one (tool/published-urls.txt).
-->
<!DOCTYPE html>
<html lang="%s">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>%s</title>
  <meta http-equiv="refresh" content="0; url=%s">
  <link rel="canonical" href="%s">
</head>
<body>
  <p><a href="%s">%s</a></p>
</body>
</html>
"""


def read_published():
    """tool/published-urls.txt: its comment header, and (path, page id, locale) rows."""
    path = os.path.join(TOOL, "published-urls.txt")
    header, rows = [], []
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                s = line.strip()
                if not s or s.startswith("#"):
                    if not rows:
                        header.append(line.rstrip("\n"))
                    continue
                parts = s.split()
                if len(parts) != 3 or parts[2] not in CODES or not parts[0].startswith("/"):
                    raise BuildError("tool/published-urls.txt: %r is not 'path page-id locale'" % s)
                rows.append(tuple(parts))
    return header, rows


def write_stubs(published):
    """A published URL this build does not write gets a stub that sends
    readers, and search engines, to where its page lives now. A URL whose
    page is gone fails the build: published URLs never just vanish."""
    have = set(S.paths.values())
    for path, pid, code in published:
        if path in have:
            continue
        if not built(pid, code):
            missing("%s was published (%s, %s) and is not built any more: restore the page, or point "
                    "its line in tool/published-urls.txt at another page id" % (path, pid, code))
            continue
        target = url(pid, code)
        title = esc(page_label(pid, code))
        write(path, STUB % (LOC[code][2], title, target, SITE + target, target, title))
        have.add(path)


def record_published(header, published):
    """--record-published: add the URL of every page this build wrote."""
    rows = list(published)
    have = {r[0] for r in rows}
    for code in S.site:
        for page in S.registry:
            path = S.paths.get((page["id"], code))
            if path and path not in have:
                rows.append((path, page["id"], code))
                have.add(path)
    put(os.path.join(S.out, "tool", "published-urls.txt"), "\n".join(header + [" ".join(r) for r in rows]) + "\n")


ROBOTS = """# Scalita Website Robots.txt
# https://scalita.com

User-agent: *
Allow: /
# The generator and its content files live in the repo, so the site serves
# them too. They are not pages.
Disallow: /tool/

# Sitemap location: an index of one sitemap per section
Sitemap: https://scalita.com/sitemap.xml
"""


def write(path, text):
    """One file of the site, named by its URL path. Nothing reaches the disk
    before every page has rendered (flush()), so a build that fails leaves
    the site as it was."""
    put(out_file(path), text)


def put(full, text):
    S.pending.append((full, text))


def flush():
    for full, text in S.pending:
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(text)
        S.written.append(full)


def write_lastmod():
    """tool/lastmod.json, in the output's tool/. A strict build keeps the
    URLs it wrote; a partial one also keeps what it skipped."""
    keep = dict(S.lastmod_old) if S.allow_missing else {}
    keep.update(S.lastmod)
    put(os.path.join(S.out, "tool", "lastmod.json"), json.dumps(keep, indent=2, sort_keys=True) + "\n")


def remove_stale():
    """Delete what an earlier build wrote and this one did not, so a renamed
    slug or a dropped page does not linger as a stray copy (a published one
    gets a stub instead). Only files carrying the build's banner, and the
    per-section sitemaps, are ever touched; tool/ and .git/ never."""
    keep = set(S.written)
    for dirpath, dirnames, filenames in os.walk(S.out):
        if dirpath == S.out:
            dirnames[:] = [d for d in dirnames if d not in (".git", "tool", "node_modules")]
        for f in filenames:
            full = os.path.join(dirpath, f)
            if full in keep:
                continue
            stale = False
            if f.endswith(".html"):
                with open(full, encoding="utf-8", errors="replace") as fh:
                    stale = GENERATED in fh.read(400)
            elif dirpath == S.out and re.fullmatch(r"sitemap-[a-z]+\.xml", f):
                stale = True
            if stale:
                os.remove(full)
                print("removed", os.path.relpath(full, S.out))
                d = dirpath
                while d != S.out and not os.listdir(d):
                    os.rmdir(d)
                    d = os.path.dirname(d)


def link_static():
    """A build outside the repo links the static parts in, so its directory
    can be served (python3 -m http.server -d DIR) and checked as it is."""
    if S.out == ROOT:
        return
    for name in STATIC:
        src, dst = os.path.join(ROOT, name), os.path.join(S.out, name)
        if os.path.exists(src) and not os.path.lexists(dst):
            os.symlink(src, dst)


