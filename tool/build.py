def page_path(page, code):
    """The URL path of a registry page in one locale. The canonical, every
    internal link, hreflang and the sitemap all use exactly this string.

    Legacy pages keep their .html URLs; every other page is a directory,
    <locale>/<section word>/<slug>/, and the section's root page sits at
    <locale>/<section word>/.
    """
    loc_path = LOC[code][1]
    if page["section"] == "legacy":
        return loc_path if page["id"] == "index" else loc_path + page["id"] + ".html"
    word = S.site[code]["sections"][page["section"]]
    if page.get("root"):
        return loc_path + word + "/"
    return loc_path + word + "/" + S.copy[(page["id"], code)]["slug"] + "/"


def url(page_id, code, frag=""):
    """Root-relative URL of a page this build writes. Never index.html."""
    try:
        return S.paths[(page_id, code)] + frag
    except KeyError:
        raise BuildError("page %r is not built in %s" % (page_id, code))


def url_abs(page_id, code):
    return SITE + url(page_id, code)


def built(page_id, code):
    return (page_id, code) in S.paths


def out_file(path):
    """The file a URL path is served from: a directory URL is its index.html."""
    p = path.lstrip("/")
    if p == "" or p.endswith("/"):
        p += "index.html"
    return os.path.join(S.out, p)


def hreflangs(code):
    """Brazilian Portuguese is the only Portuguese the site has, so it also
    answers for plain pt."""
    hl = LOC[code][3]
    return [hl, "pt"] if hl == "pt-BR" else [hl]


def alternates(page_id):
    """(code, absolute URL) for every locale the page is built in, menu order."""
    return [(l[0], SITE + S.paths[(page_id, l[0])]) for l in LOCALES if (page_id, l[0]) in S.paths]


def file_hash(path):
    """First ten hex digits of a site file's sha256, None when it is missing."""
    if path not in S.hashes:
        try:
            with open(os.path.join(ROOT, path), "rb") as fh:
                S.hashes[path] = hashlib.sha256(fh.read()).hexdigest()[:10]
        except OSError:
            S.hashes[path] = None
    return S.hashes[path]


def asset(path, v=None):
    """Root-absolute URL of a shared file, so it resolves from any depth and
    from the 404 page. CSS and JS carry ?v=<content hash> (v=True asks for
    it on anything else): Pages caches for ten minutes, and a deploy must not
    pair new HTML with an old script."""
    path = path.lstrip("/")
    u = "/" + path
    if v is None:
        v = path.endswith((".css", ".js", ".mjs"))
    if v:
        h = file_hash(path)
        if h is None:
            missing("%s does not exist" % path)
        else:
            u += "?v=" + h
    return u


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def inline_json(obj, indent=None):
    """JSON that is safe inside a <script> element: no '<' survives, so
    neither '</script>' nor '<!--' can appear in it."""
    s = json.dumps(obj, ensure_ascii=False, indent=indent,
                   separators=None if indent else (",", ":"))
    return s.replace("<", "\\u003c")


def ld_scripts(items):
    return "\n".join('  <script type="application/ld+json">\n%s\n  </script>' % inline_json(ld, indent=2)
                     for ld in items)


def play_url(code, page_id):
    """The Play link for one page, tagged so Play Console's conversion report
    says which locale (utm_source) and which page (utm_campaign) sent the
    install. The store opens in the page's language; English stays bare and
    Play picks the reader's own."""
    ref = "utm_source=scalita_%s&utm_medium=web&utm_campaign=%s" % (code, page_id)
    u = PLAY + ("" if code == "en" else "&hl=" + LOC[code][2])
    return u + "&referrer=" + quote(ref, safe="")


def play_link(code, page_id):
    """play_url() escaped for an HTML attribute."""
    return esc(play_url(code, page_id))


def head_links(loc, page):
    """canonical + the hreflang set of the locales this page is built in."""
    code = loc[0]
    out = ['  <link rel="canonical" href="%s">' % url_abs(page, code)]
    for c, href in alternates(page):
        for hl in hreflangs(c):
            out.append('  <link rel="alternate" hreflang="%s" href="%s">' % (hl, href))
    if built(page, "en"):
        out.append('  <link rel="alternate" hreflang="x-default" href="%s">' % url_abs(page, "en"))
    return "\n".join(out)


def page_label(page_id, code):
    """The short name a page goes by in the nav, footer, breadcrumb and cards."""
    page = S.by_id[page_id]
    c = S.site[code]
    if page["section"] == "legacy":
        return c["breadcrumb"]["home"] if page_id == "index" else c[page_id]["navLabel"]
    return S.copy[(page_id, code)]["label"]


def section_pages(section, code):
    return [p["id"] for p in S.registry if p["section"] == section and built(p["id"], code)]


def section_home(section, code):
    """Where the nav's Tools or Guides link goes: the section's root page, or
    else its first hub, or else its first page."""
    pages = [S.by_id[i] for i in section_pages(section, code)]
    for test in (lambda p: p.get("root"), lambda p: p["hub"], lambda p: True):
        for p in pages:
            if test(p):
                return p["id"]
    return None


def font_preload():
    """A preload for the weight the body text is set in, if style.css hosts it."""
    if S.font is None:
        S.font = ""
        try:
            with open(os.path.join(ROOT, "css", "style.css"), encoding="utf-8") as fh:
                css = fh.read()
        except OSError:
            css = ""
        for block in re.findall(r"@font-face\s*\{([^}]*)\}", css):
            src = re.search(r"url\(\s*['\"]?([^'\")]+\.woff2)['\"]?\s*\)", block)
            weight = re.search(r"font-weight:\s*(\d+)(?:\s+(\d+))?", block)
            if not src:
                continue
            lo = int(weight.group(1)) if weight else 400
            hi = int(weight.group(2)) if weight and weight.group(2) else lo
            if lo <= 400 <= hi:
                href = src.group(1)
                if not href.startswith("/"):
                    href = os.path.normpath(os.path.join("/css", href))
                S.font = href
                break
    if not S.font:
        return ""
    return '  <link rel="preload" href="%s" as="font" type="font/woff2" crossorigin>\n\n' % esc(S.font)


def lang_menu(loc, page, c):
    """A disclosure menu, not a row of buttons.

    <details> is the only native HTML that opens and closes a panel with no
    script at all: the summary is focusable, Enter and Space toggle it, and
    the links inside leave the tab order when it shuts. The script at the
    bottom of the page only adds Escape and click-outside, which are polish.

    It lists the locales this page exists in; a page that exists in none
    (the 404) offers the homes instead.
    """
    code, loc_path, _, _, _, native = loc
    if not built(page, code):
        page = "index"
    items = []
    for c2, p2, lang2, hl2, _, native2 in LOCALES:
        if not built(page, c2):
            continue
        current = ' aria-current="true"' if c2 == code else ""
        href = url(page, c2)
        items.append(
            '            <a href="%s" hreflang="%s" lang="%s"%s>%s</a>'
            % (href, hl2, lang2, current, native2)
        )
    return """        <li class="nav-lang">
          <details class="lang-menu">
            <summary aria-label="%s">
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" aria-hidden="true">
                <circle cx="12" cy="12" r="9"/>
                <path d="M3 12h18M12 3a15 15 0 010 18M12 3a15 15 0 000 18"/>
              </svg>
              <span>%s</span>
              <svg class="lang-chevron" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true">
                <polyline points="6 9 12 15 18 9"/>
              </svg>
            </summary>
            <div class="lang-list">
%s
            </div>
          </details>
        </li>""" % (esc(c["nav"]["languageLabel"] % native), esc(native), "\n".join(items))


def nav_sections(loc, page, c, indent):
    """The Tools and Guides links, for the sections this locale has pages in."""
    code = loc[0]
    here = S.by_id[page]["section"] if page in S.by_id else None
    out = ""
