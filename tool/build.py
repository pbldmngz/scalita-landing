#!/usr/bin/env python3
"""Build every page of scalita.com from the content files.

The site is still plain static HTML: this writes the HTML, git tracks the
HTML, GitHub Pages serves the HTML. Nothing runs at request time.

Why it exists: seven locales times every page is a lot of files that must
agree on the navigation, the footer, the language menu and the hreflang
links. Kept by hand that drifts within a release. Kept here it cannot.

    python3 tool/build.py                  # strict, writes into the repo
    python3 tool/build.py --out DIR        # writes the site somewhere else
    python3 tool/build.py --allow-missing  # skips what is not written yet

Edit tool/content/, never the generated .html. tool/README.md has the
layout, the contracts and the checks (python3 tool/check.py). The chrome
around every page is tool/templates/_chrome.py, the home page's content
tool/templates/home.py, every other page's body a template beside them.
"""

