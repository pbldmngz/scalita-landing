VERSION_QS = re.compile(r"\?v=[0-9a-f]+")


def stamp_lastmod(abs_url, main):
    """A page's lastmod: today when its main content changed since the build
    that wrote tool/lastmod.json (or the page is new), the recorded date when
    it did not. The hash leaves out the ?v= asset versions, which change
    with every CSS or JS edit, and everything around the main content."""
    h = hashlib.sha256(VERSION_QS.sub("", main).encode("utf-8")).hexdigest()[:16]
    prev = S.lastmod_old.get(abs_url) or {}
    if prev.get("hash") == h:
        entry = {"hash": h, "lastmod": prev["lastmod"], "since": prev.get("since", prev["lastmod"])}
    else:
        entry = {"hash": h, "lastmod": S.today, "since": prev.get("since", S.today)}
    if S.publish:
        # The commit this build is for publishes it: a change that local builds
        # dated after the last commit goes live today, and so does a new URL.
        live, published = S.publish
        if entry["lastmod"] > live:
            entry["lastmod"] = S.today
        if abs_url[len(SITE):] not in published:
            entry["since"] = S.today
    S.lastmod[abs_url] = entry
    return entry


def last_commit_date():
    """The day of the repo's last commit, which is what the site serves."""
    try:
        day = subprocess.run(["git", "-C", ROOT, "log", "-1", "--format=%cs"],
                             capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        day = ""
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", day):
        raise BuildError("--record-published dates pages against the last commit, and git log gave no date")
    return day


SITEMAPS = (("core", "legacy"), ("tools", "tools"), ("guides", "guides"))


def sitemap(section):
    """One section's urlset, and the newest lastmod in it."""
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
           '        xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    dates = []
    for code, _, _, _, _, native in LOCALES:
        pages = [p["id"] for p in S.registry if p["section"] == section and built(p["id"], code)]
        if not pages:
            continue
        out.append("  <!-- %s -->" % native)
        for pid in pages:
            u = url_abs(pid, code)
            out.append("  <url>")
            out.append("    <loc>%s</loc>" % u)
            for c2, href in alternates(pid):
                for hl in hreflangs(c2):
                    out.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>' % (hl, href))
            if built(pid, "en"):
                out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>' % url_abs(pid, "en"))
            out.append("    <lastmod>%s</lastmod>" % S.lastmod[u]["lastmod"])
            out.append("  </url>")
            dates.append(S.lastmod[u]["lastmod"])
    out.append("</urlset>")
    return ("\n".join(out) + "\n", max(dates)) if dates else (None, None)


def write_sitemaps():
    """sitemap.xml is an index of one sitemap per section, so Search
    Console's page indexing report can be read per section."""
    index = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for name, section in SITEMAPS:
        xml, last = sitemap(section)
        if xml is None:
            continue
        write("/sitemap-%s.xml" % name, xml)
        index += ["  <sitemap>",
                  "    <loc>%s/sitemap-%s.xml</loc>" % (SITE, name),
                  "    <lastmod>%s</lastmod>" % last,
                  "  </sitemap>"]
    index.append("</sitemapindex>")
    write("/sitemap.xml", "\n".join(index) + "\n")


