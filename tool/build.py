def build_sitemap():
    priority = {"index": "1.0", "support": "0.5", "privacy": "0.3", "terms": "0.3"}
    freq = {"index": "weekly", "support": "monthly", "privacy": "monthly", "terms": "monthly"}
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"',
           '        xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for code, loc_path, _, _, _, native in LOCALES:
        out.append("  <!-- %s -->" % native)
        for page in PAGES:
            out.append("  <url>")
            out.append("    <loc>%s</loc>" % page_url(loc_path, page))
            for _, p2, _, hl2, _, _ in LOCALES:
                out.append('    <xhtml:link rel="alternate" hreflang="%s" href="%s"/>'
                           % (hl2, page_url(p2, page)))
            out.append('    <xhtml:link rel="alternate" hreflang="x-default" href="%s"/>'
                       % page_url("/", page))
            out.append("    <lastmod>%s</lastmod>" % LASTMOD)
            out.append("    <changefreq>%s</changefreq>" % freq[page])
            out.append("    <priority>%s</priority>" % priority[page])
            out.append("  </url>")
    out.append("</urlset>")
    return "\n".join(out) + "\n"


