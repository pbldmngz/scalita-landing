def load_template(name):
    if name not in S.templates:
        path = os.path.join(TEMPLATES, name + ".py")
        if not os.path.exists(path):
            raise BuildError("tool/templates/%s.py does not exist" % name)
        spec = importlib.util.spec_from_file_location("scalita_template_" + name, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        if not callable(getattr(mod, "render", None)):
            raise BuildError("tool/templates/%s.py has no render(ctx)" % name)
        S.templates[name] = mod
    return S.templates[name]


def breadcrumbs(page_id, code):
    """[(label, URL)] from the locale's home down the parent chain to the page."""
    chain = []
    p = S.by_id[page_id]
    while p is not None:
        chain.append(p["id"])
        p = S.by_id[p["parent"]] if p["parent"] else None
    out = [(S.site[code]["breadcrumb"]["home"], url("index", code))]
    for pid in reversed(chain):
        if built(pid, code):
            out.append((page_label(pid, code), url(pid, code)))
    return out


def breadcrumb_ld(crumbs):
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": n + 1, "name": label, "item": SITE + href}
            for n, (label, href) in enumerate(crumbs)
        ],
    }


def page_ld(page, code, copy, stamp):
    """Article on a guide, nothing more on a tool or a hub. No WebApplication
    on the tools: Google's software app markup needs a rating or a review,
    which a free browser tool does not have, so it would only show as invalid.
    No FAQPage (retired) and no HowTo (gone since 2023)."""
    if page["hub"] or page["section"] == "tools":
        return []
    u = url_abs(page["id"], code)
    return [{
        "@context": "https://schema.org",
        "@type": "Article",
        "headline": copy.get("h1") or copy["title"],
        "description": copy["description"],
        "url": u,
        "mainEntityOfPage": u,
        "inLanguage": LOC[code][3],
        "datePublished": stamp["since"],
        "dateModified": stamp["lastmod"],
        "author": AUTHOR,
        "image": "%s/images/og-image-%s.png" % (SITE, code),
    }]


TOOL_MOUNT = re.compile(r'\bdata-tool="([a-z0-9-]+)"')


def js_files():
    """Every script under js/, as site paths, sorted."""
    if S.js is None:
        S.js = []
        for dirpath, dirnames, filenames in os.walk(os.path.join(ROOT, "js")):
            dirnames.sort()
            for f in sorted(filenames):
                if f.endswith((".js", ".mjs")):
                    S.js.append(os.path.relpath(os.path.join(dirpath, f), ROOT).replace(os.sep, "/"))
    return S.js


def asset_map():
    """{"/js/...": "/js/...?v=<hash>"} for every script: the import map, so a
    module's own imports are versioned too, and the URL to load a worklet
    from, which an import map does not reach."""
    return {"/" + p: asset(p) for p in js_files()}


STATIC_IMPORT = re.compile(r"""^\s*(?:import|export)\s+(?:[\w*${}\s,]+?\s+from\s+)?['"]([^'"]+)['"]""", re.M)


def static_imports(path, seen=None):
    """Every module a module needs before it runs, its static imports walked
    down (an import() loads later, on a tap, and is left out), repo paths."""
    seen = [] if seen is None else seen
    try:
        with open(os.path.join(ROOT, path), encoding="utf-8") as fh:
            src = fh.read()
    except OSError:
        return seen
    for spec in STATIC_IMPORT.findall(src):
        if not spec.startswith((".", "/")):
            continue
        dep = (spec.lstrip("/") if spec.startswith("/")
               else os.path.normpath(os.path.join(os.path.dirname(path), spec)).replace(os.sep, "/"))
        if dep not in seen:
            seen.append(dep)
            static_imports(dep, seen)
    return seen


def module_tags(tools):
    """The import map, a modulepreload for each module the tools import
    before they run (fetched with the page, not one round trip after its
    importer), then one module script per tool mounted on the page."""
    srcs, deps = [], []
    for t in tools:
        p = "js/tools/%s.js" % t
        if file_hash(p) is None:
            missing("%s does not exist yet, so its mount point gets no script" % p)
            continue
        srcs.append(asset(p))
        deps += [d for d in static_imports(p) if d not in deps and file_hash(d) is not None]
    if not srcs:
        return ""
    entries = {"js/tools/%s.js" % t for t in tools}
    return '  <script type="importmap">%s</script>\n%s%s' % (
        inline_json({"imports": asset_map()}),
        "".join('  <link rel="modulepreload" href="%s">\n' % asset(d) for d in deps if d not in entries),
        "\n".join('  <script type="module" src="%s"></script>' % s for s in srcs))


def piano_manifest():
    """audio/piano-web/manifest.json as a page carries it: each note's midi,
    file, duration and v (the start of its sha256, for ?v=), plus the
    top-level facts. The rest (source hashes, sizes) stays in the file: it
    is a fifth of a tool page's weight and no script reads it."""
    if S.manifest is None:
        path = os.path.join(ROOT, "audio", "piano-web", "manifest.json")
        if os.path.exists(path):
            m = load_json(path)
            S.manifest = {k: v for k, v in m.items() if k not in ("notes", "encoding")}
            S.manifest["notes"] = [
                {"midi": n["midi"], "file": n["file"], "duration": n.get("duration"),
                 "v": (n.get("sha256") or "")[:10]}
                for n in m.get("notes") or []]
        else:
            missing("audio/piano-web/manifest.json does not exist yet")
            S.manifest = False
    return S.manifest or None


