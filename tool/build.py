class BuildError(Exception):
    """A problem the build will not paper over."""


class State:
    """Everything one build reads, decides and writes."""

    def __init__(self, out, content, allow_missing, today):
        self.out = out
        self.content = content
        self.allow_missing = allow_missing
        self.today = today
        self.site = {}          # code -> tool/content/<code>.json
        self.registry = []      # tool/pages.json
        self.by_id = {}
        self.copy = {}          # (page id, code) -> tool/content/pages/<code>/<id>.json
        self.privacy_web = {}   # code -> tool/content/pages/<code>/privacy-web.json
        self.ui_names = []      # the files in tool/content/ui/en/
        self.ui = {}            # code -> {name: strings}
        self.data = {}          # stem -> tool/data/app/<stem>.json, None when missing
        self.paths = {}         # (page id, code) -> URL path, for every page built
        self.templates = {}
        self.hashes = {}
        self.font = None
        self.js = None
        self.manifest = None
        self.notes = {}
        self.lastmod_old = {}   # tool/lastmod.json as the build found it
        self.lastmod = {}       # what this build writes back
        self.publish = None     # --record-published: (date of the last commit, published paths)
        self.pending = []       # (file, text), written once everything rendered
        self.written = []
        self.warnings = []


S = None


def warn(msg):
    """Print a warning once, however many pages run into it."""
    if msg not in S.warnings:
        S.warnings.append(msg)
        print("warning: " + msg, file=sys.stderr)


def missing(msg):
    """Something not written yet: an error, or a warning with --allow-missing."""
    if S.allow_missing:
        warn(msg)
    else:
        raise BuildError(msg + " (--allow-missing builds without it)")


def rel(path):
    """A path for messages, relative to the repo when it is inside it."""
    p = os.path.relpath(path, ROOT)
    return path if p.startswith("..") else p


